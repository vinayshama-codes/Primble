def build(out_path: Path) -> str:
    """Render the PDF and return the exact text laid down, for char accounting."""
    c = canvas.Canvas(str(out_path), pagesize=LETTER)
    laid_down: list[str] = []

    for page_no, (heading, lines) in enumerate(PAGES, start=1):
        c.setFont(_BOLD, 11.5)
        c.drawString(_LEFT, _TOP + 22, heading)
        c.setFont(_FONT, 9.4)
        y = _TOP
        for line in lines:
            c.drawString(_LEFT, y, line)
            y -= _LEADING
        c.setFont(_FONT, 8)
        c.drawString(_LEFT, 42, f"Ridgeline Roofing & Sheet Metal LLC - Submission Package")
        c.drawRightString(LETTER[0] - _LEFT, 42, f"Page {page_no} of {len(PAGES)}")
        laid_down.append(heading + "\n" + "\n".join(lines))
        c.showPage()

    c.save()
    return "\n\n".join(laid_down)


