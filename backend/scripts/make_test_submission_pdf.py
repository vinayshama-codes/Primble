    out = Path(sys.argv[1] if len(sys.argv) > 1 else "test_submission_ridgeline.pdf")
    text = build(out)
    print(f"Wrote {out.resolve()}")
    print(f"Pages: {len(PAGES)}")
    print(f"Text laid down: {len(text):,} chars, {len(text.split()):,} words")
